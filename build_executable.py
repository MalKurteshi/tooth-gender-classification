#!/usr/bin/env python3
"""Build on each target OS; bundle runtime, active pipeline and seed dataset."""

import argparse
import hashlib
from pathlib import Path
import platform
import shutil
import subprocess
import sys

from src.schema import APP_VERSION, SCHEMA_VERSION, SEED_FILENAME

ROOT = Path(__file__).resolve().parent

NAME = "ToothGenderClassification"


def create_spec_file(app_type="gui"):
    name = NAME if app_type == "gui" else NAME + "-CLI"
    script = "gui_app.py" if app_type == "gui" else "predict.py"
    gui = app_type == "gui"
    datas = [
        (str(ROOT / "models" / "current" / "pipeline.joblib"), "models/current"),
        (str(ROOT / "data" / "raw" / SEED_FILENAME), "data/raw"),
    ]
    runtime_icon = (
        ROOT / "assets" / ("tooth_icon.ico" if sys.platform == "win32" else "tooth_icon.png")
    )
    datas.append((str(runtime_icon), "assets"))
    icon = ROOT / "assets" / ("tooth_icon.icns" if sys.platform == "darwin" else "tooth_icon.ico")
    spec = f"""# Generated by build_executable.py
from PyInstaller.utils.hooks import collect_submodules
hiddenimports = collect_submodules('sklearn', filter=lambda name: '.tests' not in name) + collect_submodules('imblearn', filter=lambda name: '.tests' not in name)
a = Analysis([{str(ROOT / "src" / script)!r}], pathex=[{str(ROOT / "src")!r}],
             datas={datas!r}, hiddenimports=hiddenimports, excludes=['pytest', 'IPython'])
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name={name!r}, console={not gui!r}, icon={str(icon)!r}, upx=False)
coll = COLLECT(exe, a.binaries, a.datas, name={name!r}, upx=False)
"""
    if platform.system() == "Darwin" and gui:
        spec += f"""app = BUNDLE(coll, name={NAME + ".app"!r}, bundle_identifier='com.toothgender.classification', icon={str(icon)!r},
    info_plist={{'CFBundleShortVersionString': '{APP_VERSION}', 'CFBundleVersion': '{APP_VERSION}', 'NSHighResolutionCapable': True}})
"""
    folder = ROOT / "build" / "specs"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / (name + ".spec")
    path.write_text(spec)
    return path


def build_executable(app_type="gui"):
    subprocess.run(
        [
            sys.executable,
            "-m",
            "PyInstaller",
            "--clean",
            "--noconfirm",
            "--distpath",
            str(ROOT / "dist"),
            "--workpath",
            str(ROOT / "build" / "pyinstaller"),
            str(create_spec_file(app_type)),
        ],
        cwd=ROOT,
        check=True,
    )


def create_installer_scripts():
    if sys.platform == "win32":
        compiler = shutil.which("ISCC") or shutil.which("ISCC.exe")
        if not compiler:
            fallback = Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe")
            compiler = str(fallback) if fallback.exists() else None
        if not compiler:
            raise RuntimeError("Install Inno Setup 6 to compile the Windows Setup.exe.")
        subprocess.run([compiler, str(ROOT / "packaging" / "windows.iss")], check=True)
    elif sys.platform == "darwin":
        subprocess.run(
            [
                "pkgbuild",
                "--component",
                str(ROOT / "dist" / (NAME + ".app")),
                "--install-location",
                "/Applications",
                "--scripts",
                str(ROOT / "packaging" / "macos-scripts"),
                "--identifier",
                "com.toothgender.classification",
                "--version",
                APP_VERSION,
                str(ROOT / "dist" / (NAME + "-" + APP_VERSION + ".pkg")),
            ],
            check=True,
        )
    else:
        raise RuntimeError(
            "Installer generation supports Windows and macOS. Use --no-installer on Linux."
        )


def main():
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--gui", action="store_true")
    group.add_argument("--cli", action="store_true")
    group.add_argument("--all", action="store_true")
    parser.add_argument("--no-installer", action="store_true")
    parser.add_argument(
        "--retrain-model",
        action="store_true",
        help="Explicitly regenerate the bundled seed model before building",
    )
    args = parser.parse_args()
    try:
        # Release builds freeze the reviewed model; regenerating it is an explicit action.
        import joblib
        import sklearn
        from src.predict import FEATURES, train_artifact

        model = ROOT / "models" / "current" / "pipeline.joblib"
        if args.retrain_model:
            train_artifact(ROOT / "data" / "raw" / SEED_FILENAME, model)
        artifact = joblib.load(model)
        if (
            artifact["metadata"]["sklearn_version"] != sklearn.__version__
            or artifact["metadata"]["feature_names"] != FEATURES
            or artifact["metadata"].get("schema_version") != SCHEMA_VERSION
            or artifact["metadata"].get("training_sha256")
            != hashlib.sha256((ROOT / "data" / "raw" / SEED_FILENAME).read_bytes()).hexdigest()
        ):
            raise ValueError(
                "Bundled model is incompatible. Regenerate it with --retrain-model and review the changes."
            )
        for kind in ["gui", "cli"] if args.all else ["cli"] if args.cli else ["gui"]:
            build_executable(kind)
        if not args.no_installer and not args.cli:
            create_installer_scripts()
    except Exception as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
